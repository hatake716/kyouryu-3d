#!/usr/bin/env python3
"""Extract selected source rows; never substitute a different genus or an ambiguous specimen."""
import json, hashlib, xml.etree.ElementTree as E
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];src=ROOT/'artifacts/research-models';catalog=json.loads((ROOT/'app/src/main/assets/dinosaurs.json').read_text());ids={d['id'] for d in catalog}
r=E.parse(src/'cursorial.xml');rows=[]
for row in r.find('.//table-wrap[@id="t1"]').findall('.//tr'):
    c=[''.join(x.itertext()).strip() for x in row]
    if len(c)!=6:continue
    taxon=c[0].split()[0].lower()
    if taxon not in ids or taxon in ['troodon','yutyrannus']:continue
    if taxon=='ceratosaurus' and 'nasicornis' not in c[0]:continue
    rows.append(dict(id=taxon,taxon=c[0],specimen=c[1],femurMm=float(c[2]),tibiaMm=float(c[3]),metatarsalMm=float(c[4]),source='10.1038/srep19828',table='1',scope='Hindlimb axial lengths only; outline, widths, articulation and other bones reconstructed.'))
rows.append(dict(id='stegosaurus',taxon='Stegosaurus stenops',specimen='NHMUK PV R36730 (Sophie)',femurMm=868,tibiaMm=498,metatarsalMm=100,humerusMm=450,radiusMm=312,ulnaMm=412,leftFemurMm=857,leftTibiaMm=495,source='10.1371/journal.pone.0138352',table='3',scope='Right hindlimb and forelimb lengths; left femur/tibia lengths. Other bones reconstructed. Metatarsal III available on right only; mirrored as a reconstruction on left.'))
manifest={'reviewed':'2026-09-07','units':'millimetres','sources':[{'doi':'10.1038/srep19828','authors':'W. Scott Persons IV and Philip J. Currie','year':2016,'title':'An approach to scoring cursorial limb proportions in carnivorous dinosaurs and an attempt to account for allometry','license':'CC-BY-4.0','table':'1','xmlSha256':hashlib.sha256((src/'cursorial.xml').read_bytes()).hexdigest()},{'doi':'10.1371/journal.pone.0138352','authors':'Susannah C. R. Maidment, Charlotte A. Brassey and Paul M. Barrett','year':2015,'title':'The Postcranial Skeleton of an Exceptionally Complete Individual of the Plated Dinosaur Stegosaurus stenops','license':'CC-BY-4.0','table':'3','xmlSha256':hashlib.sha256((src/'stego-xml.txt').read_bytes()).hexdigest()}],'selectionNotes':'Selected existing genera with a named specimen. Troodon excluded because of later reassignment; Yutyrannus multiple specimen entry excluded. Left/right reflection is inferred except explicitly measured Stegosaurus left femur and tibia. Historical specimen names retained as printed.','measurements':rows}
(ROOT/'docs/bone-measurements.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
lines=[]
for row in rows:
    def f(k):return str(float(row.get(k,0))/1000)+'f'
    lines.append('        '+json.dumps(row['id'])+' to LimbMeasurements('+json.dumps(row['specimen'])+', '+', '.join(f(k) for k in ['femurMm','tibiaMm','metatarsalMm','humerusMm','radiusMm','ulnaMm','leftFemurMm','leftTibiaMm'])+'),')
code='''package io.github.hatake716.dinobones.model

// Generated by tools/models/build_measurements.py from attributed primary-study tables.
// All values in metres. These measure selected bones, not a scan of the whole skeleton.
data class LimbMeasurements(val specimen: String, val femur: Float, val tibia: Float, val metatarsal: Float,
    val humerus: Float=0f, val radius: Float=0f, val ulna: Float=0f, val leftFemur: Float=0f, val leftTibia: Float=0f)
object ModelEvidence {
    val limbs=mapOf(
'''+ '\n'.join(lines)+'''
    )
    fun label(id: String) = when {
        id in DetailedModels.entries -> DetailedModels.entries.getValue(id).label
        id in limbs -> "実測の骨長に基づく復元"
        else -> "学習用・模式復元"
    }
    fun source(id: String) = when {
        id in DetailedModels.entries -> DetailedModels.entries.getValue(id).source
        id=="stegosaurus" -> "https://doi.org/10.1371/journal.pone.0138352"
        id in limbs -> "https://doi.org/10.1038/srep19828"
        else -> null
    }
    fun note(id: String): String {
        val appearance=FossilMaterials.forModel(id)?.let{"\\n\\n表面：${it.finish}\\n${FossilMaterials.NOTE}"}.orEmpty()
        return shapeNote(id)+appearance
    }
    private fun shapeNote(id: String): String {
        DetailedModels.entries[id]?.let{return it.note}
        val m=limbs[id]?:return "独自制作の学習用復元。頭骨の厚い骨壁と開口部、上下の歯列、関節端の隆起と溝、椎弓、肋骨を立体化しています。属ごとの体形を比較するためのモデルで、実測標本・正確な骨数や縮尺を再現したものではありません。表面の粒子・色むらは観察用の表現で、特定の化石の保存状態を示しません。"
        fun mm(v:Float)="${kotlin.math.round(v*1000).toInt()} mm"
        val values="大腿骨 ${mm(m.femur)}、脛骨 ${mm(m.tibia)}、第III中足骨 ${mm(m.metatarsal)}"
        val fore=if(m.humerus>0f)"。前肢は右上腕骨 ${mm(m.humerus)}、橈骨 ${mm(m.radius)}、尺骨 ${mm(m.ulna)}。左大腿骨 ${mm(m.leftFemur)}、左脛骨 ${mm(m.leftTibia)} も反映" else ""
        val credit=if(id=="stegosaurus")"Maidment・Brassey・Barrett（2015）表3、CC BY 4.0" else "Persons・Currie（2016）表1、CC BY 4.0"
        return "標本：${m.specimen}\\n$values$fore。これらの骨の最大長を3D形状の長軸に反映しています。\\n\\n骨の断面、関節の角度、頭骨・胴・尾などの未計測部は模式復元で、実物スキャンではありません。左右別の値がない骨は片側の寸法を反転して補っています。全長をこの属全体の確定値として示すものではありません。表面の色・微細な凹凸は独自表現です。\\n\\n出典：$credit（数値をメートルへ換算し立体化）。"
    }
}
'''
(ROOT/'app/src/main/java/io/github/hatake716/dinobones/model/ModelEvidence.kt').write_text(code)
print('Generated',len(rows),'measured taxa')
