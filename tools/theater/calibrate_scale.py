#!/usr/bin/env python3
"""Calibrate shared scene metres without changing source vertices or observation models."""
from pathlib import Path
import json,gzip,struct,re
ROOT=Path(__file__).resolve().parents[2]
ASSETS=ROOT/'app/src/main/assets'
# These are display reference lengths, not measurements of the downloaded replicas.
REFERENCES={
 'tyrannosaurus':(12.3,'Field Museum / SUE: 40.5 ft。別標本を参考にした展示用の全長目安。SUEのスキャンではない。','https://www.fieldmuseum.org/blog/how-well-do-you-know-sue'),
 'patagotitan':(37.5,'Natural History Museum / Patagotitan: 37.5 m。推定全長であり個々の標本の測定値ではない。','https://www.nhm.ac.uk/discover/dino-directory/patagotitan.html'),
 'brachiosaurus':(22.0,'Natural History Museum / Brachiosaurus: 22 m。頭尾方向をこの全長目安に換算。高さ・姿勢は模式復元に由来。','https://www.nhm.ac.uk/discover/dino-directory/brachiosaurus.html'),
}
def calibrate():
 rows=json.loads((ASSETS/'theater/manifest.json').read_text());catalog={x['id']:x for x in json.loads((ASSETS/'dinosaurs.json').read_text())}
 code=[];notes=['館内の縮尺と資料（確認日：2026-09-08）','', '館内の1単位は1 m。視点の高さは1.7 m、床の小目地は1 mです。実寸単位がある19モデルはその単位を保持します。他のモデルは図鑑に記載した推定全長・翼開長の代表値へ一様に換算します。全長は頭尾方向の幅、翼開長は左右の翼の幅に対応させた近似です。体の曲がり方、形状、姿勢によって実際の全長・高さとは差があり、全骨の正確さや同じ成長段階を保証しません。','', '「縮尺未確定」の5種は信頼できる全身寸法がないため、実物サイズとして扱わない参考展示です。小型の標本は模型を拡大せず、観察しやすい高さの台に載せています。個別の「3D骨格」と採用した骨長の資料は従来どおりです。','']
 for row in rows:
  id=row['id'];d=catalog[id];dims=[b-a for a,b in zip(row['min'],row['max'])]
  p=ASSETS/'specimens'/f'{id}.ksmz'
  if not p.exists():p=ROOT/'artifacts/theater-1.6/sources'/f'{id}.ksmz'
  with gzip.open(p,'rb') as f:magic,count,metres,radius=struct.unpack('<4sIff',f.read(16))
  axis=2 if '翼開長' in d['size'] else 0
  sources=[x['url'] for x in d['sources']]
  if metres>0:
   scale=metres;target=dims[axis]*scale;basis='specimen_units' if id=='triceratops' else 'measured_bones'
   label=f'標本の前後幅 {target:.2f} m' if id=='triceratops' else f'骨長資料による復元・前後幅 {target:.2f} m'
   note='元のモデルのm単位を保持。全身には博物館での補作・組み立てを含む。' if id=='triceratops' else '選択した標本の実測骨長による換算を保持。未計測部は模式復元で、この属の成体全長の確定値ではない。'
   sources=[('https://3d.si.edu/object/3d/triceratops-horridus-marsh-1889:3c0a5623-2dd2-4d45-a394-027425c6cb54' if id=='triceratops' else 'https://doi.org/10.1371/journal.pone.0138352' if id=='stegosaurus' else 'https://doi.org/10.1038/srep19828')]
   if id=='triceratops':sources=[json.loads((ROOT/'docs/specimen-provenance.json').read_text())['objectUrl']]
  else:
   size=d['size'];found=re.search(r'(\d+(?:\.\d+)?)(?:[〜～–-](\d+(?:\.\d+)?))?\s*m',size)
   if id in REFERENCES:
    target,note,url=REFERENCES[id];sources=[url];basis='estimated_length'
   elif found:
    target=(float(found[1])+float(found[2] or found[1]))/2;basis='estimated_span' if axis==2 else 'estimated_length'
    note=f'図鑑の「{size}」から代表値を採用。推定幅がある場合は範囲の中間値。形状全体を一様に拡縮し、頭尾方向（翼竜は翼端間）を合わせた近似。'
   else:
    target=None;basis='unresolved';note=f'図鑑の記載：{size}。全身の実寸に換算できないため、従来の参考模型サイズを保持。'
   scale=target/dims[axis] if target is not None else 1.0
   label=('翼開長の目安' if axis==2 else '全長の目安')+f' {target:g} m' if target is not None else '縮尺未確定・参考展示'
  width,height,depth=[v*scale for v in dims];base=.95 if height<1.2 else .18
  row['scale']=scale
  row['calibration']={'basis':basis,'axis':'wing_span_z' if axis==2 else 'length_x','referenceMeters':target,'label':label,'note':note,'sources':sources,'baseMeters':base,'reviewed':'2026-09-08'}
  row['change']=row['change'].replace('exhibition scale, not a measurement model','shared metre scene; scale basis and uncertainty recorded in calibration')
  args=', '.join(f'{v:.8f}f' for v in [scale,width,height,depth,base])
  code.append(f'        "{id}" to ExhibitScale({args}, "{label}", "{basis}"),')
  notes += [d['name']+' / '+d['latin'],label,note,*sources,'']
 payload=json.dumps(rows,ensure_ascii=False,indent=2)+'\n'
 (ASSETS/'theater/manifest.json').write_text(payload);(ROOT/'docs/theater-mesh-provenance.json').write_text(payload)
 (ASSETS/'theater/scale-notes.txt').write_text('\n'.join(notes))
 (ROOT/'app/src/main/java/io/github/hatake716/dinobones/theater/ExhibitScales.kt').write_text('''package io.github.hatake716.dinobones.theater

// Generated by tools/theater/calibrate_scale.py; source URLs and uncertainty are in the manifest.
data class ExhibitScale(val scale:Float,val width:Float,val height:Float,val depth:Float,val baseY:Float,val label:String,val basis:String)
object ExhibitScales {
    val entries=mapOf(
'''+ '\n'.join(code)+'\n    )\n}\n')
 print('Calibrated',len(rows),'exhibits; verified units:',sum(x['calibration']['basis'] in ('specimen_units','measured_bones') for x in rows),'unresolved:',sum(x['calibration']['basis']=='unresolved' for x in rows))
if __name__=='__main__':calibrate()
